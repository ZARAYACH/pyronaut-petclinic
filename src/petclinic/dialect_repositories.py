"""Environment-selected JDBC implementations of the shared query contracts.

The direct CRUD bases and repeated query declarations are intentional SDK
adaptations. Nested CRUD inheritance loses generic signatures, while inherited
query declarations can share another dialect's SQL. See PORT-035/039 in the
issue log before simplifying this structure. Persistence remains generated by
Micronaut Data for every database.
"""

from typing import Protocol

